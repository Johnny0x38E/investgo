func cnEquitySeeds(symbols ...string) []hotSeed {
	return buildNamedSeeds("CN-A", "CNY", cnEquitySeedNames, symbols)
}

func cnETFSeeds(symbols ...string) []hotSeed {
	return buildNamedSeeds("CN-ETF", "CNY", cnETFSeedNames, symbols)
}

func hkEquitySeeds(codes ...string) []hotSeed {
	return buildNamedSeeds("HK-MAIN", "HKD", hkEquitySeedNames, codes)
}

func buildNamedSeeds(market, currency string, names map[string]string, symbols []string) []hotSeed {
	seen := make(map[string]struct{}, len(symbols))
	seeds := make([]hotSeed, 0, len(symbols))
	for _, symbol := range symbols {
		if _, exists := seen[symbol]; exists {
			continue
		}
		seen[symbol] = struct{}{}
		seeds = append(seeds, hotSeed{
			Symbol:   symbol,
			Name:     provider.FirstNonEmpty(names[symbol], symbol),
			Market:   market,
			Currency: currency,
		})
	}
	return seeds
}
